"""Generate Databricks SQL DDL from the table specs.

Everything here is pure string generation: nothing runs SQL. The bundle
template's setup job executes the output, and CI compares it with the
checked-in snapshot so the SQL can never drift from ``tables.py``.
"""

from __future__ import annotations

import re
from collections.abc import Iterable

from lakehouse_runledger._version import __version__
from lakehouse_runledger.schema.tables import ALL_TABLES, Column, TableSpec

_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_PREFIX = re.compile(r"^[A-Za-z0-9_]*$")


def _check_identifier(value: str, what: str) -> str:
    if not _IDENTIFIER.match(value):
        raise ValueError(
            f"{what} must be a simple identifier (letters, digits, underscore; not starting "
            f"with a digit), got {value!r}"
        )
    return value


def quote_identifier(value: str) -> str:
    """Backtick-quote one identifier part. Rejects anything that is not a simple identifier."""
    return f"`{_check_identifier(value, 'identifier')}`"


def sql_string(value: str) -> str:
    """Render a Databricks SQL string literal."""
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def table_fqn(spec: TableSpec, catalog: str, schema: str, prefix: str = "rl_") -> str:
    """Fully qualified, quoted table name, e.g. ``main`.`ops`.`rl_events``."""
    if not _PREFIX.match(prefix):
        raise ValueError(f"prefix may contain only letters, digits and underscore, got {prefix!r}")
    _check_identifier(catalog, "catalog")
    _check_identifier(schema, "schema")
    return ".".join(quote_identifier(p) for p in (catalog, schema, spec.table_name(prefix)))


def _column_sql(column: Column) -> str:
    parts = [quote_identifier(column.name), column.type]
    if not column.nullable:
        parts.append("NOT NULL")
    if column.comment:
        parts.append(f"COMMENT {sql_string(column.comment)}")
    return " ".join(parts)


def create_table_sql(spec: TableSpec, catalog: str, schema: str, prefix: str = "rl_") -> str:
    """``CREATE TABLE IF NOT EXISTS`` statement for one spec."""
    lines = [f"CREATE TABLE IF NOT EXISTS {table_fqn(spec, catalog, schema, prefix)} ("]
    lines.append(",\n".join(f"  {_column_sql(c)}" for c in spec.columns))
    lines.append(")")
    lines.append("USING DELTA")
    if spec.cluster_by:
        keys = ", ".join(quote_identifier(k) for k in spec.cluster_by)
        lines.append(f"CLUSTER BY ({keys})")
    if spec.comment:
        lines.append(f"COMMENT {sql_string(spec.comment)}")
    props = spec.table_properties()
    if props:
        rendered = ",\n".join(
            f"  {sql_string(k)} = {sql_string(v)}" for k, v in sorted(props.items())
        )
        lines.append(f"TBLPROPERTIES (\n{rendered}\n)")
    return "\n".join(lines) + ";"


def add_columns_sql(
    spec: TableSpec,
    existing_columns: Iterable[str],
    catalog: str,
    schema: str,
    prefix: str = "rl_",
) -> str | None:
    """Additive migration: ``ALTER TABLE ... ADD COLUMNS`` for spec columns the table lacks.

    Returns ``None`` when nothing is missing. Added columns are always nullable,
    because existing rows have no value for them.
    """
    existing = {c.lower() for c in existing_columns}
    missing = [c for c in spec.columns if c.name not in existing]
    if not missing:
        return None
    rendered = ",\n".join(
        f"  {_column_sql(Column(c.name, c.type, nullable=True, comment=c.comment))}"
        for c in missing
    )
    return f"ALTER TABLE {table_fqn(spec, catalog, schema, prefix)} ADD COLUMNS (\n{rendered}\n);"


def render_tables_script(
    catalog: str,
    schema: str,
    prefix: str = "rl_",
    tables: Iterable[TableSpec] = ALL_TABLES,
    *,
    include_version: bool = True,
) -> str:
    """The full table-creation script, as run by the bundle's setup job."""
    header = ["-- Generated by `runledger ddl`. Do not edit by hand; edit schema/tables.py."]
    if include_version:
        header.append(f"-- runledger {__version__}")
    body = [create_table_sql(t, catalog, schema, prefix) for t in tables]
    return "\n".join(header) + "\n\n" + "\n\n".join(body) + "\n"
